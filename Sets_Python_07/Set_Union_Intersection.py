# Union Operation can be performed on two sets to combined the data
# Intersection Operation can be performed on two sets to get its common data.

a = {10, 20, 30}
b = {10, 50, 60, 40}

print(" ---To get Both sets combined data using 'union' --- ")
c = a.union(b)
print(c)

print("\n")
print(" ---To get Both sets common data using 'union' --- ")
d = a.intersection(b)
print(d)

