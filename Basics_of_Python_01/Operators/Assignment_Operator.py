#Assignment Operator ('='): is used to assign values to variables 

#Compound assignment operators in python 

print(r" (+=) means: L = L + R | a = a + b ")
print(r" (-=) means: L = L - R | a = a - b ")
print(r" (*=) means: L = L * R | a = a * b ")
print(r" (/=) means: L = L / R | a = a / b ")
print(r" (%=) means: L = L % R | a = a % b ")
print(r" (**=) means: L = L ** R | a = a ** b ")
print(r" (//=) means: L = L // R | a = a // b ")
