# What is Escape Sequence: A Sequence of characters which has indirect meaning which is placed 
# in double quotes " "

print(r" --- To Print like: 'Happy New Year' without space we can use '\t' between strings ---")
 #Here adding of 'r' at starting meaning that ignoring all Escape

print("Happy\tnew\tYear")
print("\n")
print(r"--- '\n' we used in Escape Sequence to add new line")
print("Hello \nWorld ")

print(r"\n")
print(r"--- To add single quote we use ' \' ' ")
print("Hello \'world\' ")

print(r"\n")
print(r"--- To add Double quote we use ' \" ' ")
print("Hello \"World\" ")
